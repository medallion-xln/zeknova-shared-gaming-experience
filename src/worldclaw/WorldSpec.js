/**
 * ZekNova — WorldClaw world specification
 * Location: /src/worldclaw/WorldSpec.js
 *
 * The canonical, machine-readable description of a ZekNova world.
 *
 * ── WHY A SPEC AT ALL ────────────────────────────────────────────────────
 * Today ZekNova's world is *code*: `assets/environment-runtime.js` holds the
 * Desert civilisation as eleven structures at hand-typed offsets, and there is
 * nothing anywhere that states why the water-collector tower stands at
 * (-11, -24). A world that is code can be read by a human and by nothing else.
 * It cannot be planned, validated, critiqued, repaired, diffed, streamed,
 * persisted, or regenerated.
 *
 * A WorldSpec is the same world as *data*: intent, constraints and placements
 * in one frozen object that every other WorldClaw stage reads and writes.
 *
 * ── THE DETERMINISM CONTRACT ─────────────────────────────────────────────
 * The whole subsystem rests on one promise:
 *
 *     worldSeed + worldSpec + generatorVersion  ->  byte-identical world
 *
 * `specDigest()` is what makes that promise checkable. It is a stable FNV-1a
 * over a canonical serialisation (keys sorted, numbers quantised), so two specs
 * that describe the same world hash the same regardless of key insertion order
 * or floating-point noise below the quantisation step. Persistence stores the
 * digest; a load that re-derives a different digest is a *detected* divergence
 * rather than a world that silently drifted.
 *
 * Numbers are quantised to 1e-6 deliberately. Terrain sampling and placement
 * solving both produce values whose last bits differ between engines; without
 * quantisation the digest would be an engine fingerprint rather than a world
 * fingerprint.
 *
 * ── WHAT THIS MODULE IS NOT ──────────────────────────────────────────────
 * It has no Three.js import, no DOM access and no I/O. It is pure data plus
 * pure functions, so the whole schema is testable under plain `node` and the
 * validator can run server-side, in a worker, or in a test — which is what
 * makes "AI proposes, deterministic code disposes" enforceable rather than
 * aspirational.
 */

/**
 * Bumped whenever generation OUTPUT changes for an unchanged spec+seed.
 * Persistence pins it: a saved world generated by an older version is replayed
 * from its stored placements instead of being silently regenerated differently.
 */
export const GENERATOR_VERSION = "worldclaw-1.0.0";

/** Schema version of the spec document itself, independent of the generator. */
export const WORLD_SPEC_VERSION = 1;

/** Matches the live runtime (`Be.worldSize`, `Be.waterLevel` in the bundle). */
export const WORLD_DEFAULTS = Object.freeze({
  worldSize: 180,
  waterLevel: -0.35,
  playableHalfExtent: 84,
  heightGridSize: 129,
});

/** Region archetypes ZekNova understands. Extending this is additive. */
export const BIOME_KINDS = Object.freeze([
  "forest", "desert", "highlands", "arctic", "wetlands",
  // Transition archetypes — the reason terrain can read as continuous rather
  // than as five abutting rectangles.
  "canyon", "mesa", "dunes", "alpine", "coastline", "basin",
]);

export const CLIMATE_KINDS = Object.freeze([
  "arid", "temperate", "montane", "polar", "humid", "transitional",
]);

export const TRAVERSAL_ROLES = Object.freeze([
  "blocking", "cover", "walkable", "climbable", "decorative", "landmark",
]);

export const GAMEPLAY_ROLES = Object.freeze([
  "settlement", "infrastructure", "resource", "objective", "hazard",
  "ambience", "navigation", "boss", "discovery",
]);

/* ── canonical serialisation ───────────────────────────────────────────── */

const QUANTUM = 1e6;

function quantise(value) {
  if (!Number.isFinite(value)) return 0;
  // `+ 0` collapses -0 to 0 so two specs that differ only in the sign of zero
  // do not hash differently.
  return Math.round(value * QUANTUM) / QUANTUM + 0;
}

/**
 * Deterministic JSON. Object keys are emitted in sorted order and every finite
 * number is quantised, so the output depends only on the world being described.
 */
export function canonicalise(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return JSON.stringify(quantise(value));
  if (typeof value === "boolean" || typeof value === "string") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalise).join(",")}]`;
  if (typeof value === "object") {
    const keys = Object.keys(value).filter((key) => value[key] !== undefined).sort();
    return `{${keys.map((key) => `${JSON.stringify(key)}:${canonicalise(value[key])}`).join(",")}}`;
  }
  return "null";
}

/** FNV-1a over a string — the same hash the runtime already uses for seeds. */
export function fnv1a(text) {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

/**
 * Stable digest of a spec. Two specs describing the same world share a digest;
 * any semantic change moves it. Rendered as 8 hex chars prefixed with the
 * generator version so a digest can never be compared across generators by
 * accident.
 */
export function specDigest(spec) {
  return `${GENERATOR_VERSION}:${fnv1a(canonicalise(spec)).toString(16).padStart(8, "0")}`;
}

/**
 * Derive a numeric seed for any sub-generator from the world seed plus a label.
 * Every generator draws its randomness through this, so adding a new generator
 * cannot shift the output of an existing one — a property a single shared
 * cursor-style PRNG would not have.
 */
export function deriveSeed(worldSeed, label) {
  return fnv1a(`${worldSeed >>> 0}:${label}`);
}

/* ── construction ──────────────────────────────────────────────────────── */

const emptyRegionArrays = () => ({
  materials: [], settlements: [], landmarks: [], vegetation: [],
  resources: [], creatures: [], enemies: [], missionHooks: [], bossHooks: [],
  /* Gameplay zones (Phase 10). Every generated region must expose these, and
     they are part of the spec rather than derived at load time so a persisted
     world restores its mission surface without re-running generation. */
  zones: [],
});

/**
 * Normalise a partial region into the full shape. Callers may write terse
 * regions; everything downstream reads a complete one, so no stage needs its
 * own defaulting and two stages cannot disagree about what "missing" means.
 */
export function normaliseRegion(region = {}, index = 0) {
  const bounds = region.bounds ?? {};
  return {
    id: String(region.id ?? `region-${index}`),
    biome: String(region.biome ?? "highlands"),
    kind: String(region.kind ?? region.biome ?? "highlands"),
    bounds: {
      minX: quantise(Number(bounds.minX ?? -18)),
      maxX: quantise(Number(bounds.maxX ?? 18)),
      minZ: quantise(Number(bounds.minZ ?? -90)),
      maxZ: quantise(Number(bounds.maxZ ?? 90)),
    },
    center: {
      x: quantise(Number(region.center?.x ?? ((bounds.minX ?? -18) + (bounds.maxX ?? 18)) / 2)),
      z: quantise(Number(region.center?.z ?? ((bounds.minZ ?? -90) + (bounds.maxZ ?? 90)) / 2)),
    },
    elevation: {
      base: quantise(Number(region.elevation?.base ?? 3.15)),
      relief: quantise(Number(region.elevation?.relief ?? 4)),
      ridged: quantise(Number(region.elevation?.ridged ?? 0.5)),
    },
    climate: String(region.climate ?? "temperate"),
    dangerLevel: Math.max(0, Math.min(10, Math.round(Number(region.dangerLevel ?? 3)))),
    terrain: { ...(region.terrain ?? {}) },
    /* Planning intent, carried through so a saved world records WHY it was
       built this way and a regeneration can reproduce the same decisions. */
    plan: region.plan ? { ...region.plan } : null,
    neighbourBiomes: Array.isArray(region.neighbourBiomes) ? [...region.neighbourBiomes] : [],
    // Every list key exists on every region, always, even when empty. A stage
    // that has to test `region.enemies?.length` is a stage that will one day
    // forget to.
    ...Object.fromEntries(Object.keys(emptyRegionArrays()).map((key) => [
      key, Array.isArray(region[key]) ? region[key].map((entry) => ({ ...entry })) : [],
    ])),
  };
}

/**
 * Build a complete, frozen WorldSpec from a partial description.
 * Freezing is not decoration: every downstream stage receives the same object,
 * and a critic that could mutate the spec it is grading would make its own
 * score meaningless.
 */
export function createWorldSpec(input = {}) {
  const regions = (Array.isArray(input.regions) ? input.regions : []).map(normaliseRegion);
  const spec = {
    specVersion: WORLD_SPEC_VERSION,
    generatorVersion: GENERATOR_VERSION,
    worldId: String(input.worldId ?? "zeknova-world"),
    seed: Number(input.seed ?? 0) >>> 0,
    planet: "ZekNova",
    intent: input.intent ? String(input.intent) : null,
    world: {
      worldSize: quantise(Number(input.world?.worldSize ?? WORLD_DEFAULTS.worldSize)),
      waterLevel: quantise(Number(input.world?.waterLevel ?? WORLD_DEFAULTS.waterLevel)),
      playableHalfExtent: quantise(Number(input.world?.playableHalfExtent ?? WORLD_DEFAULTS.playableHalfExtent)),
      heightGridSize: Math.round(Number(input.world?.heightGridSize ?? WORLD_DEFAULTS.heightGridSize)),
    },
    regions,
    /* Adjacency and transition edges. This is what lets terrain read
       desert -> canyon -> highlands instead of desert | highlands. */
    relationships: (input.relationships ?? []).map((rel) => ({
      from: String(rel.from), to: String(rel.to),
      kind: String(rel.kind ?? "adjacent"),
      blendWidth: quantise(Number(rel.blendWidth ?? 8)),
    })),
    traversal: {
      roads: (input.traversal?.roads ?? []).map((road) => ({ ...road })),
      rivers: (input.traversal?.rivers ?? []).map((river) => ({ ...river })),
      bridges: (input.traversal?.bridges ?? []).map((bridge) => ({ ...bridge })),
      portals: (input.traversal?.portals ?? []).map((portal) => ({ ...portal })),
      fastTravelNodes: (input.traversal?.fastTravelNodes ?? []).map((node) => ({ ...node })),
      corridors: (input.traversal?.corridors ?? []).map((corridor) => ({ ...corridor })),
    },
    atmosphere: {
      skyPreset: String(input.atmosphere?.skyPreset ?? "zeknova-twin-sun"),
      fogDensity: quantise(Number(input.atmosphere?.fogDensity ?? 0.012)),
      sunCount: Math.round(Number(input.atmosphere?.sunCount ?? 2)),
      ...(input.atmosphere ?? {}),
    },
    globalRules: {
      maxSlopeForBuild: quantise(Number(input.globalRules?.maxSlopeForBuild ?? 3.3)),
      minBuildHeightAboveWater: quantise(Number(input.globalRules?.minBuildHeightAboveWater ?? 0.8)),
      maxBuildHeight: quantise(Number(input.globalRules?.maxBuildHeight ?? 18)),
      utilityRange: { power: 30, water: 36, data: 36, ...(input.globalRules?.utilityRange ?? {}) },
      ...(input.globalRules ?? {}),
    },
  };
  spec.digest = specDigest({ ...spec, digest: undefined });
  return deepFreeze(spec);
}

export function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const key of Object.keys(value)) deepFreeze(value[key]);
  }
  return value;
}

/* ── validation ────────────────────────────────────────────────────────── */

/**
 * Structural and semantic validation. Returns findings rather than throwing,
 * because the planner needs to iterate on a spec and the repair director needs
 * to know *which* rule failed, not merely that something did.
 *
 * Severity: "error" blocks generation; "warning" is recorded and shipped.
 */
export function validateWorldSpec(spec) {
  const errors = [];
  const warnings = [];
  const fail = (code, message) => errors.push({ code, message });
  const warn = (code, message) => warnings.push({ code, message });

  if (!spec || typeof spec !== "object") {
    return { valid: false, errors: [{ code: "spec.missing", message: "No spec supplied." }], warnings: [] };
  }
  if (spec.specVersion !== WORLD_SPEC_VERSION) fail("spec.version", `Unsupported specVersion ${spec.specVersion}.`);
  if (spec.planet !== "ZekNova") fail("spec.planet", "WorldClaw only generates ZekNova.");
  if (!Number.isInteger(spec.seed) || spec.seed < 0) fail("spec.seed", "seed must be a non-negative integer.");
  if (!Array.isArray(spec.regions) || spec.regions.length === 0) fail("spec.regions", "A world needs at least one region.");

  const half = spec.world?.playableHalfExtent ?? WORLD_DEFAULTS.playableHalfExtent;
  const ids = new Set();

  for (const region of spec.regions ?? []) {
    const at = `region "${region.id}"`;
    if (ids.has(region.id)) fail("region.duplicate", `Duplicate region id ${region.id}.`);
    ids.add(region.id);
    if (!BIOME_KINDS.includes(region.biome)) fail("region.biome", `${at} uses unknown biome "${region.biome}".`);
    if (!CLIMATE_KINDS.includes(region.climate)) warn("region.climate", `${at} uses unknown climate "${region.climate}".`);

    const { minX, maxX, minZ, maxZ } = region.bounds;
    if (!(maxX > minX) || !(maxZ > minZ)) fail("region.bounds", `${at} has a degenerate footprint.`);
    if (minX < -half || maxX > half || minZ < -half || maxZ > half) {
      fail("region.outOfWorld", `${at} extends past the playable half-extent (${half}).`);
    }

    for (const settlement of region.settlements) {
      if (!Number.isFinite(settlement.x) || !Number.isFinite(settlement.z)) {
        fail("settlement.position", `${at} has a settlement with a non-finite position.`);
      }
      if (!Array.isArray(settlement.structures)) {
        fail("settlement.structures", `${at} settlement "${settlement.id}" has no structure list.`);
      }
    }
    for (const hook of region.missionHooks) {
      if (!hook.missionId) fail("missionHook.id", `${at} has a mission hook with no missionId.`);
      if (!Number.isFinite(hook.x) || !Number.isFinite(hook.z)) {
        fail("missionHook.position", `${at} mission hook "${hook.missionId}" has no usable position.`);
      }
    }
    for (const hook of region.bossHooks) {
      if (!hook.bossId) fail("bossHook.id", `${at} has a boss hook with no bossId.`);
      if (!(Number(hook.arenaRadius) > 0)) fail("bossHook.arena", `${at} boss hook "${hook.bossId}" has no arena footprint.`);
    }
  }

  for (const rel of spec.relationships ?? []) {
    if (!ids.has(rel.from) || !ids.has(rel.to)) {
      fail("relationship.dangling", `Relationship ${rel.from}->${rel.to} names a region that does not exist.`);
    }
  }

  // A region that no relationship reaches produces a hard visual seam, because
  // nothing tells the blend field how to cross into it.
  if ((spec.regions?.length ?? 0) > 1) {
    const linked = new Set((spec.relationships ?? []).flatMap((rel) => [rel.from, rel.to]));
    for (const region of spec.regions) {
      if (!linked.has(region.id)) warn("region.isolated", `Region "${region.id}" has no adjacency; its border will read as a hard seam.`);
    }
  }

  return { valid: errors.length === 0, errors, warnings };
}

/** Convenience: every settlement structure in the spec, flattened. */
export function allStructures(spec) {
  const out = [];
  for (const region of spec.regions ?? []) {
    for (const settlement of region.settlements ?? []) {
      for (const structure of settlement.structures ?? []) {
        out.push({ ...structure, regionId: region.id, settlementId: settlement.id });
      }
    }
  }
  return out;
}

/** Every placed object in the spec, whatever kind it is. */
export function allPlacements(spec) {
  const out = [];
  for (const region of spec.regions ?? []) {
    for (const key of ["landmarks", "vegetation", "resources"]) {
      for (const entry of region[key] ?? []) out.push({ ...entry, regionId: region.id, category: key });
    }
    for (const settlement of region.settlements ?? []) {
      for (const structure of settlement.structures ?? []) {
        out.push({ ...structure, regionId: region.id, settlementId: settlement.id, category: "structure" });
      }
    }
  }
  return out;
}
