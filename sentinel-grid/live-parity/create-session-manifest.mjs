import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)));
const marker = JSON.parse(await readFile(path.join(root, '..', 'integration.json'), 'utf8'));
const args = process.argv.slice(2);
const get = (flag) => { const i = args.indexOf(flag); if (i < 0 || !args[i + 1]) throw new Error(`Missing ${flag}`); return args[i + 1]; };
const sessionId = get('--session-id');
const environmentId = get('--environment-id');
const repositoryHead = get('--repository-head');
const runtimeBuildHash = get('--runtime-build-hash');
const collectorId = get('--collector-id');
const startedAt = get('--started-at');
const endedAt = get('--ended-at');
const output = path.resolve(get('--output'));
const campaignFile = path.resolve(args.includes('--campaign') ? get('--campaign') : path.join(marker.kernelPath, 'artifacts', 'r0-runtime-identity', 'stage2f-campaign-manifest.json'));
const moduleUrl = pathToFileURL(path.join(marker.kernelPath, 'src', 'lab', 'zeknova-controlled-evaluation.js')).href;
const { buildZekNovaSessionManifest } = await import(moduleUrl);
const names = (await readdir(path.join(root, 'records'))).filter((name) => name.endsWith('.json')).sort();
const all = await Promise.all(names.map(async (name) => JSON.parse(await readFile(path.join(root, 'records', name), 'utf8'))));
const records = all.filter((record) => record.context?.sessionId === sessionId);
const campaignManifest = JSON.parse(await readFile(campaignFile, 'utf8'));
const manifest = buildZekNovaSessionManifest({ sessionId, environmentId, repositoryHead, runtimeBuildHash, collectorId, startedAt, endedAt, records, campaignManifest });
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `${JSON.stringify(manifest, null, 2)}\n`);
console.log(JSON.stringify(manifest, null, 2));
